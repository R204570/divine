def avg(series, f):
    out = []
    for m in range(12):
        vals = [f(series[y][m]) for y in YEARS if m < len(series[y])]
        out.append(sum(vals) / len(vals))
    return out


def norm(v):
    mx = max(v)
    return [round(100 * x / mx) for x in v]


